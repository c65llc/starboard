// Package generate builds the pages Starboard writes under
// <content>/generated/: app-map.md (a Mermaid map of every navigation
// edge), screens.md (the screen catalog) and one wireframe SVG per screen
// per form factor. All is a pure function of the loaded project, so the
// bytes are the same on every run and every OS; Diff compares them with
// what is on disk.
package generate

import (
	"bytes"
	"cmp"
	"errors"
	"fmt"
	"io/fs"
	"maps"
	"path"
	"slices"
	"strings"

	"github.com/c65llc/starboard/internal/project"
	"github.com/c65llc/starboard/internal/registry"
	"github.com/c65llc/starboard/internal/render"
)

// header opens every generated Markdown page.
const header = "<!-- Generated by starboard. Do not edit. -->\n"

// LargeMap is the screen count past which app-map.md adds a map per area.
const LargeMap = 60

// Dir is the project-relative generated directory, <content>/generated,
// and false when the content root is not a valid relative slash path (Load
// has already reported it as path-invalid).
func Dir(p *project.Project) (string, bool) {
	content := path.Clean(p.Config.Content)
	if strings.Contains(content, `\`) || !fs.ValidPath(content) {
		return "", false
	}
	return path.Join(content, "generated"), true
}

// All returns every generated file, keyed by project-relative slash path.
// A project with no screens generates nothing (an empty, non-nil map); one
// whose content root is invalid gives nil.
func All(p *project.Project) map[string][]byte {
	dir, ok := Dir(p)
	if !ok {
		return nil
	}
	out := map[string][]byte{}
	if len(p.Registry.Screens) == 0 {
		return out
	}
	g := newGraph(p)
	out[path.Join(dir, "app-map.md")] = []byte(g.appMap())
	out[path.Join(dir, "screens.md")] = []byte(g.screens(dir))
	for _, s := range g.ordered {
		for _, ff := range FormFactors(p, s) {
			out[path.Join(dir, "wireframes", wireframe(s.ID, ff))] = render.Wireframe(s, ff, p.Config.FormFactors[ff])
		}
	}
	return out
}

// MermaidID is a screen ID as a Mermaid node ID: "." becomes "_" and "-"
// becomes "__".
//
// The encoding is injective over screen IDs, so two screens never share a
// node. An ID holds only [a-z0-9.-], and every "." is followed by a letter,
// so a run of underscores in the output comes from a run of hyphens and at
// most one dot, which ends the run. A run of even length 2k is k hyphens;
// odd length 2k+1 is k hyphens then a dot. The output decodes uniquely.
func MermaidID(id string) string {
	return strings.NewReplacer(".", "_", "-", "__").Replace(id)
}

// FormFactors are the configured form factors s is drawn on: those of each
// of its platforms, in config platform order, each once. A form factor the
// config does not define is left out.
func FormFactors(p *project.Project, s *registry.Screen) []string {
	var out []string
	for _, pl := range Platforms(p, s) {
		for _, ff := range p.Config.Platforms[pl].FormFactors {
			if _, ok := p.Config.FormFactors[ff]; ok && !slices.Contains(out, ff) {
				out = append(out, ff)
			}
		}
	}
	return out
}

// Platforms is s's configured platforms in config order: every platform
// when s names none.
func Platforms(p *project.Project, s *registry.Screen) []string {
	if len(s.Platforms) == 0 {
		return p.Config.PlatformOrder
	}
	var out []string
	for _, pl := range p.Config.PlatformOrder {
		if slices.Contains(s.Platforms, pl) {
			out = append(out, pl)
		}
	}
	return out
}

func wireframe(id, ff string) string { return id + "." + ff + ".svg" }

// Kind is how a generated file differs from the disk.
type Kind string

// The kinds of Change.
const (
	Changed Kind = "changed" // on disk with other bytes
	Missing Kind = "missing" // generated but not on disk
	Extra   Kind = "extra"   // an owned file on disk that is no longer generated
)

// Change is one file under generated/ that is not as All would write it.
type Change struct {
	Path string
	Kind Kind
}

// Owned reports whether name, a project-relative slash path, is one of the
// files generate can write: <content>/generated/app-map.md,
// <content>/generated/screens.md, or <content>/generated/wireframes/<name>.svg
// directly in wireframes/. Nothing else under generated/ is starboard's, so
// nothing else is ever reported or removed: with content ".", generated/ may
// well hold another tool's files.
func Owned(p *project.Project, name string) bool {
	dir, ok := Dir(p)
	if !ok {
		return false
	}
	rest, ok := strings.CutPrefix(name, dir+"/")
	if !ok {
		return false
	}
	if rest == "app-map.md" || rest == "screens.md" {
		return true
	}
	svg, ok := strings.CutPrefix(rest, "wireframes/")
	return ok && !strings.Contains(svg, "/") && strings.HasSuffix(svg, ".svg")
}

// Diff compares want, as All gives it, with the files generate owns (see
// Owned) in p.FS, and returns the differences sorted by path. Any other
// file, under the generated directory or not, is never considered. A
// missing generated directory just means every wanted file is missing.
func Diff(p *project.Project, want map[string][]byte) ([]Change, error) {
	dir, ok := Dir(p)
	if !ok {
		return nil, nil
	}
	onDisk, err := ownedFiles(p, dir)
	if err != nil {
		return nil, err
	}
	var out []Change
	for _, name := range onDisk {
		if _, ok := want[name]; !ok {
			out = append(out, Change{name, Extra})
		}
	}
	for _, name := range slices.Sorted(maps.Keys(want)) {
		data, err := fs.ReadFile(p.FS, name)
		switch {
		case errors.Is(err, fs.ErrNotExist):
			out = append(out, Change{name, Missing})
		case err != nil:
			return nil, err
		case !bytes.Equal(data, want[name]):
			out = append(out, Change{name, Changed})
		}
	}
	slices.SortFunc(out, func(a, b Change) int { return strings.Compare(a.Path, b.Path) })
	return out, nil
}

// ownedFiles lists the regular files in dir and dir/wireframes that Owned
// accepts. A missing directory holds none.
func ownedFiles(p *project.Project, dir string) ([]string, error) {
	var out []string
	for _, d := range []string{dir, path.Join(dir, "wireframes")} {
		entries, err := fs.ReadDir(p.FS, d)
		if errors.Is(err, fs.ErrNotExist) {
			continue
		}
		if err != nil {
			return nil, err
		}
		for _, e := range entries {
			if name := path.Join(d, e.Name()); !e.IsDir() && Owned(p, name) {
				out = append(out, name)
			}
		}
	}
	return out, nil
}

// edge is one navigation between two screens.
type edge struct{ from, to string }

// graph is the project's screens in catalog order and the edges of their
// default layouts.
type graph struct {
	p       *project.Project
	areas   []string                      // config areas with screens, then other areas, sorted
	byArea  map[string][]*registry.Screen // each sorted by ID
	ordered []*registry.Screen            // by area, then ID
	to      map[string][]string           // every target of each screen, sorted, each once
	from    map[string][]string           // every screen reaching each target, sorted, each once
	edges   []edge                        // between registered screens, sorted, each once
}

func newGraph(p *project.Project) *graph {
	g := &graph{p: p, byArea: map[string][]*registry.Screen{}, to: map[string][]string{}, from: map[string][]string{}}
	for _, id := range slices.Sorted(maps.Keys(p.Registry.Screens)) {
		s := p.Registry.Screens[id]
		g.byArea[s.Area] = append(g.byArea[s.Area], s)
		for _, e := range registry.Edges(s, "") {
			if !slices.Contains(g.to[id], e.To) {
				g.to[id] = append(g.to[id], e.To)
			}
		}
	}
	for _, a := range p.Config.Areas {
		if len(g.byArea[a]) > 0 && !slices.Contains(g.areas, a) {
			g.areas = append(g.areas, a)
		}
	}
	for _, a := range slices.Sorted(maps.Keys(g.byArea)) {
		if !slices.Contains(g.areas, a) {
			g.areas = append(g.areas, a)
		}
	}
	for _, a := range g.areas {
		g.ordered = append(g.ordered, g.byArea[a]...)
	}
	for _, from := range slices.Sorted(maps.Keys(g.to)) {
		for _, to := range g.to[from] { // Edges sorts by target
			g.from[to] = append(g.from[to], from)
			if _, ok := p.Registry.Screens[to]; ok {
				g.edges = append(g.edges, edge{from, to})
			}
		}
	}
	return g
}

// node is a Mermaid node for a screen.
func node(id string) string {
	return MermaidID(id) + `["` + mermaidLabel(id) + `"]`
}

// mermaidLabel is text on one line, escaped for a quoted Mermaid label.
func mermaidLabel(s string) string { return strings.ReplaceAll(oneLine(s), `"`, "#quot;") }

// mdEscaper backslash-escapes the characters that would make text a link,
// an HTML tag or a code span in Markdown.
var mdEscaper = strings.NewReplacer(`\`, `\\`, "[", `\[`, "]", `\]`, "<", `\<`, ">", `\>`, "`", "\\`")

// md is s on one line, escaped for Markdown text.
func md(s string) string { return mdEscaper.Replace(oneLine(s)) }

func (g *graph) appMap() string {
	var b strings.Builder
	b.WriteString(header + "\n# App map\n\n")
	g.flowchart(&b, g.areas, g.edges, nil)
	if len(g.p.Registry.Screens) > LargeMap {
		for _, a := range g.areas {
			in := map[string]bool{}
			for _, s := range g.byArea[a] {
				in[s.ID] = true
			}
			var edges []edge
			var outside []string
			for _, e := range g.edges {
				if !in[e.from] {
					continue
				}
				edges = append(edges, e)
				if !in[e.to] && !slices.Contains(outside, e.to) {
					outside = append(outside, e.to)
				}
			}
			slices.Sort(outside)
			b.WriteString("\n## " + md(a) + "\n\n")
			g.flowchart(&b, []string{a}, edges, outside)
		}
	}
	return b.String()
}

// flowchart writes a Mermaid block: a subgraph per area, the outside nodes,
// then the edges.
func (g *graph) flowchart(b *strings.Builder, areas []string, edges []edge, outside []string) {
	b.WriteString("```mermaid\nflowchart LR\n")
	for _, a := range areas {
		n := slices.Index(g.areas, a) + 1
		fmt.Fprintf(b, "  subgraph area%d[\"%s\"]\n", n, mermaidLabel(a))
		for _, s := range g.byArea[a] {
			b.WriteString("    " + node(s.ID) + "\n")
		}
		b.WriteString("  end\n")
	}
	for _, id := range outside {
		b.WriteString("  " + node(id) + "\n")
	}
	for _, e := range edges {
		b.WriteString("  " + MermaidID(e.from) + " --> " + MermaidID(e.to) + "\n")
	}
	b.WriteString("```\n")
}

func (g *graph) screens(dir string) string {
	var b strings.Builder
	b.WriteString(header + "\n# Screens\n")
	usedIn := g.flowsByScreen()
	for _, a := range g.areas {
		b.WriteString("\n## " + md(a) + "\n")
		for _, s := range g.byArea[a] {
			g.screen(&b, s, dir, usedIn[s.ID])
		}
	}
	return b.String()
}

func (g *graph) screen(b *strings.Builder, s *registry.Screen, dir string, flows []string) {
	platforms := Platforms(g.p, s)
	fmt.Fprintf(b, "\n### %s (`%s`)\n\n", md(s.Title), s.ID)
	b.WriteString("- Purpose: " + cmp.Or(md(s.Purpose), "none") + "\n")
	b.WriteString("- Presentation: " + s.Presentation + "\n")
	b.WriteString("- Status: " + status(s, platforms) + "\n")
	b.WriteString("- Platforms: " + cmp.Or(strings.Join(platforms, ", "), "none") + "\n\n")

	if ffs := FormFactors(g.p, s); len(ffs) > 0 {
		for _, ff := range ffs {
			fmt.Fprintf(b, "![%s on %s](wireframes/%s)\n", s.ID, ff, wireframe(s.ID, ff))
		}
	} else {
		b.WriteString("No form factor configured.\n")
	}

	var files, shots []string
	for _, pl := range keysInOrder(g.p.Config.PlatformOrder, s.Files) {
		for _, f := range s.Files[pl] {
			files = append(files, pl+": ["+md(f)+"]("+target(rel(dir, f))+")")
		}
	}
	for _, pl := range keysInOrder(g.p.Config.PlatformOrder, s.Screenshots) {
		shots = append(shots, fmt.Sprintf("%s: ![%s on %s](%s)", pl, s.ID, pl, target(rel(dir, s.Screenshots[pl]))))
	}
	list(b, "Files", files)
	list(b, "Screenshots", shots)
	list(b, "Navigates to", code(g.to[s.ID]))
	list(b, "Reached from", code(g.from[s.ID]))
	list(b, "Used in flows", flows)
}

// flowsByScreen lists, for each screen ID, a link to every flow that names
// it (flows.Flow.Screens: the entry or any reference), sorted by flow file.
func (g *graph) flowsByScreen() map[string][]string {
	out := map[string][]string{}
	for _, stem := range slices.Sorted(maps.Keys(g.p.Flows)) {
		f := g.p.Flows[stem]
		link := "[" + cmp.Or(md(f.Title), md(stem)) + "](" + target("../flows/"+stem+".md") + ")"
		for _, id := range f.Screens() {
			out[id] = append(out[id], link)
		}
	}
	return out
}

// status is s's status: one word, or "platform: status" for each platform
// when it varies by platform.
func status(s *registry.Screen, platforms []string) string {
	if len(s.Status.Per) == 0 {
		return s.Status.For("")
	}
	var parts []string
	for _, pl := range platforms {
		parts = append(parts, pl+": "+s.Status.For(pl))
	}
	return cmp.Or(strings.Join(parts, ", "), s.Status.For(""))
}

// keysInOrder is m's keys: those in order first, as order has them, then
// the rest sorted.
func keysInOrder[V any](order []string, m map[string]V) []string {
	var out []string
	for _, k := range order {
		if _, ok := m[k]; ok {
			out = append(out, k)
		}
	}
	for _, k := range slices.Sorted(maps.Keys(m)) {
		if !slices.Contains(out, k) {
			out = append(out, k)
		}
	}
	return out
}

// list writes "<label>:" and a bullet per item, or "<label>: none.".
func list(b *strings.Builder, label string, items []string) {
	if len(items) == 0 {
		b.WriteString("\n" + label + ": none.\n")
		return
	}
	b.WriteString("\n" + label + ":\n\n")
	for _, it := range items {
		b.WriteString("- " + it + "\n")
	}
}

func code(ids []string) []string {
	out := make([]string, len(ids))
	for i, id := range ids {
		out[i] = "`" + id + "`"
	}
	return out
}

// oneLine collapses s's whitespace, newlines included, to single spaces.
func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

// target is a Markdown link target, in angle brackets when it holds a
// space or a parenthesis.
func target(p string) string {
	if strings.ContainsAny(p, " ()") {
		return "<" + p + ">"
	}
	return p
}

// rel is the slash path from directory from to the file to, both relative
// to the project root.
func rel(from, to string) string {
	f := strings.Split(path.Clean(from), "/")
	t := strings.Split(path.Clean(to), "/")
	i := 0
	for i < len(f) && i < len(t)-1 && f[i] == t[i] {
		i++
	}
	parts := slices.Repeat([]string{".."}, len(f)-i)
	return path.Join(append(parts, t[i:]...)...)
}
