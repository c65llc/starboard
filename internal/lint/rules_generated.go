package lint

import (
	"github.com/c65llc/starboard/internal/diag"
	"github.com/c65llc/starboard/internal/generate"
	"github.com/c65llc/starboard/internal/project"
)

// ruleGeneratedStale reports each file under <content>/generated/ that is
// out of date, missing, or not one generate writes, against
// Context.Generated. A nil Generated is not checked.
func ruleGeneratedStale(p *project.Project, c *Context) []diag.Diagnostic {
	if c.Generated == nil {
		return nil
	}
	fix := &diag.Fix{Description: "run starboard generate"}
	changes, err := generate.Diff(p, c.Generated)
	if err != nil {
		dir, _ := generate.Dir(p)
		return []diag.Diagnostic{{
			Rule: "generated-stale", File: dir, Fix: fix,
			Message: "cannot check generated files: " + err.Error(),
		}}
	}
	var out []diag.Diagnostic
	for _, ch := range changes {
		msg := ch.Path + " is out of date"
		switch ch.Kind {
		case generate.Missing:
			msg = ch.Path + " is missing"
		case generate.Extra:
			msg = ch.Path + " is not generated by starboard; remove it"
		}
		out = append(out, diag.Diagnostic{Rule: "generated-stale", File: ch.Path, Message: msg, Fix: fix})
	}
	return out
}
